"""Synthetic fixtures for the custom detector, built in memory.

All of them are inert: the only script is app.alert(1), stream contents are short text and
nothing exploits anything. They carry exactly the syntax the custom detector inspects.
"""

import zlib

from tests.pdf_fixtures import make_pdf


def stream_object(dictionary: str, data: bytes) -> str:
    """An object body "<< dictionary /Length n >> stream ... endstream" (binary-safe via latin-1)."""
    return f"<< {dictionary} /Length {len(data)} >>\nstream\n{data.decode('latin-1')}\nendstream"


# ----------------------------------------------------------------------------- positive

OBFUSCATED_ACTION = "<< /Type /Action /S /J#61vaScript /J#53 (app.alert\\(1\\);) >>"


def obfuscated_javascript_pdf(in_object_stream: bool = False) -> bytes:
    """/OpenAction -> a JavaScript action whose /S /JavaScript and /JS names are #-escaped.
    With in_object_stream, the action lives in a FlateDecode object stream (object 6)."""
    return make_pdf(catalog_extra="/OpenAction 5 0 R", objects={5: OBFUSCATED_ACTION},
                    compressed={5} if in_object_stream else set())


def obfuscated_filter_pdf() -> bytes:
    """The obfuscated action inside an object stream whose filter is written /Fl#61teDecode, so
    that neither the action nor the filter name appears as plain text. (Cross-reference offsets
    after the object stream shift by two bytes; a sequential lexer does not use them.)"""
    return obfuscated_javascript_pdf(in_object_stream=True).replace(b"/Filter /FlateDecode", b"/Filter /Fl#61teDecode")


def name_in_comment_pdf() -> bytes:
    """An escaped /JavaScript name inside a comment line (object 5), as a desynchronising
    file could hide it from a sequential reader."""
    return make_pdf(objects={5: "<< /Type /Annot >>\n% /S /J#61vaScript"})


# ----------------------------------------------------------------------------- negative

def plain_pdf() -> bytes:
    return make_pdf()


def plain_javascript_pdf() -> bytes:
    """Unobfuscated JavaScript: active content, but no obfuscation (the PDF scanner's job)."""
    return make_pdf(catalog_extra="/OpenAction 5 0 R",
                    objects={5: "<< /Type /Action /S /JavaScript /JS (app.alert\\(1\\);) >>"})


def necessary_escapes_pdf() -> bytes:
    """Escapes that the specification requires: a space and a slash inside names, plus a
    literal string and a comment that merely mention names."""
    return make_pdf(objects={
        5: "<< /Type /Font /Subtype /Type1 /BaseFont /Arial#20Bold /Note (see /Arial#20Bold) >>",
        6: "<< /Type /EmbeddedFile /Subtype /text#2Fplain >>\n% generated by /my#2Ftool",
    })


# ----------------------------------------------------------------------------- coverage limits

OBJSTM = "/Type /ObjStm /N 1 /First 4"


def ascii85_stream_pdf() -> bytes:
    return make_pdf(objects={5: stream_object(f"{OBJSTM} /Filter /ASCII85Decode", b"87cURD]i,\"Ebo80~>")})


def truncated_flate_pdf() -> bytes:
    return make_pdf(objects={5: stream_object(f"{OBJSTM} /Filter /FlateDecode",
                                              zlib.compress(b"9 0 << /Type /XObject >> " * 50)[:-12])})


def obfuscated_content_stream_pdf() -> bytes:
    """An escaped name inside an ordinary (non-object) stream: content, not object syntax."""
    return make_pdf(objects={5: stream_object("/Filter /FlateDecode", zlib.compress(b"/J#53 (inert text)"))})


# ----------------------------------------------------------------------------- malformed

def no_objects_pdf() -> bytes:
    return b"%PDF-1.7\nthis is not a PDF body\n%%EOF\n"


def unterminated_string_pdf() -> bytes:
    return make_pdf(objects={5: "<< /Title (never closed >>"})


def unterminated_stream_pdf() -> bytes:
    return b"%PDF-1.7\n1 0 obj\n<< /Length 10 >>\nstream\nno end marker follows"
